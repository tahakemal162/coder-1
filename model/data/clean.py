"""Veri temizleme — filtreler + tekilleştirme. Sahte veri yok: girdi gerçek koddur."""
import hashlib
import re

MIN_CHARS = 40
MAX_LINE = 2000          # devasa minify satırları at
MAX_AUTO_GEN = 0.5       # satırların yarısından çoğu tekrarlıysa at

GEN_MARKS = re.compile(r"(generated by|auto-generated|do not edit|autogenerated)", re.I)


def looks_like_code(text):
    """Basit sezgisel: kod olmayan dökümanları elemek için."""
    if not text or len(text) < MIN_CHARS:
        return False
    if GEN_MARKS.search(text[:2000]):
        return False
    lines = text.splitlines()
    if any(len(l) > MAX_LINE for l in lines):
        return False
    if lines:
        uniq = len(set(lines))
        if uniq / len(lines) < (1 - MAX_AUTO_GEN):
            return False
    return True


class Dedup:
    """Dosya/pencere düzeyinde içerik-hash tekilleştirme."""

    def __init__(self):
        self.seen = set()

    def is_new(self, text):
        h = hashlib.sha1(text.encode("utf-8", errors="ignore")).digest()[:12]
        if h in self.seen:
            return False
        self.seen.add(h)
        return True
